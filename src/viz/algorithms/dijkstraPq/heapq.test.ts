describe("heapq port", () => {
  it("keeps the list in exactly CPython's order after every push and pop", () => {
    const heap: HeapItem[] = [];
    for (const [op, item, after] of PYTHON_OPS) {
      if (op === "push") heappush(heap, item);
      else expect(heappop(heap)).toEqual(item);
      expect(heap).toEqual(after);
    }
  });

  it("compares tuples the way Python does", () => {
    expect(tupleLess([1, "b"], [2, "a"])).toBe(true);
    expect(tupleLess([2, "a"], [2, "b"])).toBe(true);
    expect(tupleLess([2, "b"], [2, "b"])).toBe(false);
    expect(tupleLess([2], [2, "a"])).toBe(true);
    expect(tupleLess([Infinity, "a"], [3, "z"])).toBe(false);
  });
});
